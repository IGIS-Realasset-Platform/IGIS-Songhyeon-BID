export function deliverableForSonghyeonTask(sourceKey) {
  const workstreamKey = sourceKey.replace(/-T\d+$/, '');
  const deliverables = deliverablesByWorkstream[workstreamKey];
  if (!deliverables?.length) throw new Error(`공식 산출물 매핑 누락: ${sourceKey}`);
  const taskNumber = Number(sourceKey.match(/-T(\d+)$/)?.[1] || 1);
  return deliverables[Math.min(taskNumber - 1, deliverables.length - 1)];
}

